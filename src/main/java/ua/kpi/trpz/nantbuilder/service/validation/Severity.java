package ua.kpi.trpz.nantbuilder.service.validation;

/**
 * Рівень проблеми, знайденої під час перевірки скрипта.
 */
public enum Severity {
    /** Помилка: скрипт не можна зберегти або експортувати. */
    ERROR,
    /** Попередження: скрипт працюватиме, але, імовірно, не так, як очікується. */
    WARNING
}
